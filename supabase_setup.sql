-- 1. Удаление старой таблицы, если существовала (аккуратно при пересоздании)
DROP TABLE IF EXISTS dishes CASCADE;

-- 2. Создание таблицы блюд
CREATE TABLE public.dishes (
    id BIGINT PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
    name TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('Супы', 'Горячее', 'Гарниры', 'Салаты', 'Выпечка и напитки')),
    price INTEGER NOT NULL CHECK (price >= 0),
    weight INTEGER NOT NULL CHECK (weight >= 0),
    calories INTEGER NOT NULL CHECK (calories >= 0),
    proteins NUMERIC(5,1) NOT NULL DEFAULT 0,
    fats NUMERIC(5,1) NOT NULL DEFAULT 0,
    carbs NUMERIC(5,1) NOT NULL DEFAULT 0,
    ingredients TEXT NOT NULL,
    image TEXT NOT NULL,
    in_stock BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Включаем Row Level Security (RLS)
ALTER TABLE public.dishes ENABLE ROW LEVEL SECURITY;

-- Создаем политику публичного чтения меню (любой посетитель может просматривать блюда)
CREATE POLICY "Allow public read access to dishes" 
ON public.dishes 
FOR SELECT 
USING (true);

